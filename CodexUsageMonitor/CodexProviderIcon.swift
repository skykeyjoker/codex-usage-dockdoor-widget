import AppKit
import SwiftUI

enum CodexProviderBrand {
    case codex
    case cursor
    case claude
}

/// Official provider marks rendered from the SVG templates used by CodexBar.
/// NSImage keeps the embedded SVG as a vector representation at small sizes.
struct CodexProviderIcon: View {
    let brand: CodexProviderBrand
    let size: CGFloat
    var color: Color = .primary

    var body: some View {
        Group {
            if brand == .claude {
                Image(systemName: "asterisk").font(.system(size: size, weight: .heavy))
            } else if let image = CodexProviderIconAssets.image(for: brand) {
                Image(nsImage: image)
                    .resizable()
                    .renderingMode(.template)
                    .interpolation(.high)
                    .aspectRatio(contentMode: .fit)
            } else {
                Image(systemName: brand == .codex ? "terminal.fill" : "cube.fill")
                    .resizable()
                    .aspectRatio(contentMode: .fit)
            }
        }
        .foregroundStyle(color)
        .frame(width: size, height: size)
        .accessibilityHidden(true)
    }
}

