    static func image(for brand: CodexProviderBrand) -> NSImage? {
        switch brand {
        case .codex: codex
        case .cursor: cursor
        case .claude: nil
        }
    }

    private static func makeImage(base64: String) -> NSImage? {
        guard let data = Data(base64Encoded: base64, options: .ignoreUnknownCharacters),
              let image = NSImage(data: data)
        else { return nil }
        image.isTemplate = true
        return image
    }
